#!/usr/bin/env python3
"""Fill .onsite_env from the repo's private data. Run on an organizer's machine, not on the MacBooks.

Reads .env, sitedata/ and local/mirex/ (none of them committed). Rewrites only the part of .onsite_env
under the GENERATED line, so the lines above it survive.

  uv run python onsit-kit/make_env.py
"""

import csv
import json
import os
import re
import sys
from datetime import datetime
from pathlib import Path

import dotenv
import pytz
import yaml

KIT = Path(__file__).resolve().parent
ROOT = KIT.parent
sys.path[:0] = [str(ROOT), str(KIT)]
import materials  # noqa: E402
from utils.shared import event_link  # noqa: E402

ENV_FILE = KIT / '.onsite_env'
TEMPLATE = KIT / 'onsite_env.example'
GENERATED = '# ----- GENERATED by make_env.py: edits below this line are overwritten -----'
GITHUB = 'https://github.com/Daniel-Chin/ISMIR2026-Kit'
SHEETS = [
    ('PAPERS_SHEET_URL', 'Papers', 'Paper metadata, media links'),
    ('EVENTS_SHEET_URL', 'Events', 'The schedule; each event\'s Zoom, Slack and room'),
    ('SESSION_ASSIGNMENT_SHEET_URL', 'Session assignment', 'Which paper is in which session'),
    ('LBDS_SHEET_URL', 'LBDs', 'LBD metadata, media links'),
    ('LBDS_GROUPING', 'LBD groups', 'LBD topics and their Slack channels'),
]


def read_csv(path):
    with open(path, newline='', encoding='utf-8-sig') as f:
        return list(csv.DictReader(f))


def iso_time(day, clock, zone):
    return zone.localize(datetime.strptime(f'{day} {clock}', '%Y-%m-%d %H:%M')).isoformat()


def link_rows(config, events):
    site = config['miniconf_url'].rstrip('/')
    shared = [e['live_url'] for e in events if e['category'] == 'LBD' and e['live_url']]
    rows = [
        ('Conference', 'Miniconf', site, 'The virtual platform'),
        ('Conference', 'Schedule', f'{site}/calendar.html', 'Full calendar'),
        ('Conference', 'Live Overview', f'{site}/live.html', 'What is live now, with headcounts'),
        ('Conference', 'Papers', f'{site}/papers.html', 'All papers and sessions'),
        ('Conference', 'LBDs', f'{site}/lbds.html', 'Late-Breaking/Demo list'),
        ('Conference', 'Warm-up Discussion', f'{site}/lounge.html', 'Paper and LBD discussion boards'),
        ('Conference', 'Official website', config['official_site_url'], 'ISMIR 2026 main site'),
        ('Zoom', 'Shared webinar', shared[0] if shared else '', 'Join link of every non-poster live event, LBD included'),
        ('Zoom', 'Zoom web portal', 'https://zoom.us/profile', 'Account settings and recordings'),
        ('Slack', 'Workspace', 'https://ismir2026.slack.com', 'Conference Slack'),
        ('Slack', 'Helpdesk', config['helpdesk_url'], 'Helpdesk channel'),
        ('YouTube', 'Channel', config['youtube_channel_url'], 'Presentation videos'),
        ('YouTube', 'LBD playlist', config['lbd_youtube_playlist_url'], 'All LBD videos'),
        ('YouTube', 'YouTube Studio', 'https://studio.youtube.com', 'Log in as zoom.admin.ismir2026@gmail.com'),
        ('Operations', 'GitHub repo', GITHUB, 'This kit and the website code'),
        ('Operations', 'Refresh website', f'{GITHUB}/actions/workflows/refresh-website.yml',
         'Rebuild the miniconf from the Live Database'),
    ]
    for key, name, description in SHEETS:
        url = os.environ.get(key, '').strip().strip('"')
        if url:
            rows.append(('Live Database', name, url, description))
        else:
            print(f'{key} is not in .env: left out of the links table')
    return rows


def poster_sessions(events, site, zone):
    return [{
        'title': e['title'],
        'start': iso_time(e['start_date'], e['start_time'], zone),
        'end': iso_time(e['start_date'], e['end_time'], zone),
        'location': e['onsite_location'],
        'zoom': e['live_url'],
        'slack': e['channel_url'],
        'miniconf': f'{site}/{event_link(e)}',
    } for e in events if e['category'] == 'Poster session']


def mirex_folders(root, rows):
    """uid -> its Drive folder, which is named after the task: found through the links in the sheet."""
    folders = {}
    for entry in materials.list_folder(root):
        files = {file['id'] for file in materials.list_folder(entry['id'])}
        for row in rows:
            if re.search(r'[?&]id=([\w-]+)', row['raw_video_path'])[1] in files:
                folders[row['uid']] = entry['name']
    return folders


def merge_mirex(sheet_rows, mirex_rows):
    """The sheet may already list MIREX entries, and is the newer of the two."""
    listed = {row['uid'] for row in sheet_rows}
    return sheet_rows + [row for row in mirex_rows if row['uid'] not in listed]


def lbd_rows(rows, folders):
    return [{
        'uid': r['uid'],
        'title': r['title'],
        'authors': re.sub(r'\s*\([^)]*\)|\*', '', r['authors_and_affil_from_pdf']),
        'mode': r['presentation_mode'],
        'folder': folders.get(r['uid'], r['uid']),
    } for r in rows]


def main():
    dotenv.load_dotenv(ROOT / '.env')
    config = yaml.safe_load((ROOT / 'sitedata' / 'config.yml').read_text(encoding='utf-8'))
    zone = pytz.timezone(config['timezone'])
    events = read_csv(ROOT / 'sitedata' / 'events.csv')
    lbd_event = next(e for e in events if e['category'] == 'LBD')
    mirex = ROOT / 'local' / 'mirex' / 'lbds_mirex.csv'
    if not mirex.exists():
        raise SystemExit(f'Missing {mirex}: screen 7 would have no entries')
    source = ENV_FILE if ENV_FILE.exists() else TEMPLATE
    by_hand = source.read_text(encoding='utf-8').split(GENERATED)[0].rstrip()
    drive = dict(re.findall(r'^DRIVE_FOLDER_(\w+)=(\S+)', by_hand, re.M))
    if not {'LBD', 'MIREX'} <= set(drive) or 'example' in by_hand.split('DRIVE_FOLDER_')[1]:
        raise SystemExit('Set DRIVE_FOLDER_LBD and DRIVE_FOLDER_MIREX in .onsite_env first')
    mirex_rows = read_csv(mirex)
    folders = mirex_folders(materials.folder_id(drive['MIREX']), mirex_rows)
    for row in mirex_rows:
        if row['uid'] not in folders:
            print(f'{row["uid"]}: not found in the MIREX Drive folder')
    lbds = lbd_rows(merge_mirex(read_csv(ROOT / 'sitedata' / 'lbds.csv'), mirex_rows), folders)

    lines = [
        f'ONSITE_TIMEZONE={config["timezone"]}',
        f'ONSITE_LBD_START={iso_time(lbd_event["start_date"], lbd_event["start_time"], zone)}',
        f'ONSITE_LBD_END={iso_time(lbd_event["start_date"], lbd_event["end_time"], zone)}',
    ]
    materials_links = [('Materials', f'{name} Drive folder', link, 'Camera-ready materials; see the Materials page')
                       for name, link in drive.items()]
    for index, row in enumerate(link_rows(config, events) + materials_links, start=1):
        lines.append(f'LINK_AUTO_{index}=' + ' | '.join(row))
    sessions = poster_sessions(events, config['miniconf_url'].rstrip('/'), zone)
    lines.append('ONSITE_POSTER_SESSIONS=' + json.dumps(sessions, ensure_ascii=False))
    lines.append('ONSITE_LBDS=' + json.dumps(lbds, ensure_ascii=False))

    ENV_FILE.write_text('\n'.join([by_hand, '', GENERATED, *lines, '']), encoding='utf-8')
    print(f'{ENV_FILE.name}: {len(sessions)} poster sessions, {len(lbds)} LBDs')


if __name__ == '__main__':
    main()
