#!/usr/bin/env python3
"""Build the static Pre-Conference Lounge into preconf/build, for merging into the miniconf build.

Same contract as live_overview/scripts/build_miniconf.py (see preconf/integration.md):
  build/lounge.html   the page (its own nav, linked from the miniconf)
  build/lounge/       scripts, styles, the frozen paper data and site-config.js
Nothing else under build/ is written or removed.

The page talks to the Cloudflare Worker (src/, deployed separately) at --api-origin, or at
$PRECONF_API_ORIGIN. Paper data is re-frozen from sitedata on every run.

  python scripts/build_miniconf.py [--mockup] [--out build] [--api-origin https://…]
"""
import argparse
import json
import os
import re
import shutil
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlsplit

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_data  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parent
PUBLIC = ROOT / "public"
PAGE = "lounge.html"
ASSET_DIR = "lounge"
DEFAULT_API_ORIGIN = "https://lounge.liweilin.org"   # custom domain; *.workers.dev is blocked on some networks
# Files the page loads; everything else in public/ (local probes, etc.) stays out of the build.
ASSETS = ["app.js", "board.js", "room.js", "api.js", "canon-egg.js", "theme.js", "styles.css"]
ASSET_DIRS = ["vendor", "data"]


def render_page(text, api_origin):
    # Root-absolute paths were written for the Worker; on the miniconf they live under lounge/.
    text = re.sub(r'(src|href)="/(?!/)([^"]*)"', lambda m: f'{m[1]}="{ASSET_DIR}/{m[2]}"', text)
    # GitHub Pages cannot send headers, so the CSP the Worker sends goes in a meta tag.
    ws = re.sub(r"^http", "ws", api_origin)
    csp = (f"default-src 'self'; base-uri 'none'; object-src 'none'; script-src 'self'; "
           f"style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self' {api_origin} {ws}; "
           f"form-action {api_origin}")
    meta = f'  <meta http-equiv="Content-Security-Policy" content="{csp}" />\n  <meta name="referrer" content="strict-origin-when-cross-origin" />\n'
    return text.replace('  <meta name="viewport"', meta + '  <meta name="viewport"', 1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mockup", action="store_true", help="read ../sitedata_mock instead of ../sitedata")
    ap.add_argument("--out", type=Path, default=ROOT / "build")
    ap.add_argument("--api-origin", default=os.environ.get("PRECONF_API_ORIGIN") or DEFAULT_API_ORIGIN)
    args = ap.parse_args()

    api = args.api_origin.rstrip("/")
    parts = urlsplit(api)
    local = parts.hostname in ("localhost", "127.0.0.1")   # local cross-origin testing only
    if parts.scheme not in (("https", "http") if local else ("https",)) or not parts.netloc or parts.path:
        sys.exit(f"--api-origin must be an https origin, got {api!r}")

    sitedata = REPO / ("sitedata_mock" if args.mockup else "sitedata")
    sys.argv = [sys.argv[0], "--sitedata", str(sitedata)]
    build_data.main()   # refresh public/data/program.json and public/vendor/

    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=out) as tmp:
        stage = Path(tmp)
        assets = stage / ASSET_DIR
        assets.mkdir()
        for name in ASSETS:
            shutil.copy2(PUBLIC / name, assets / name)
        for name in ASSET_DIRS:
            shutil.copytree(PUBLIC / name, assets / name)
        tz = build_data.read_simple_yaml(sitedata / "config.yml").get("timezone") or "Asia/Dubai"
        (assets / "site-config.js").write_text(
            "// Generated by scripts/build_miniconf.py: this copy of the page talks to the Worker below.\n"
            f"window.PC_CONFIG = {json.dumps({'apiOrigin': api, 'timeZone': tz})};\n"
            "// The shared time-zone picker reads the venue zone from window.ISMIRSite (see live_overview).\n"
            "window.ISMIRSite = window.ISMIRSite || { timeZone: window.PC_CONFIG.timeZone };\n",
            encoding="utf-8",
        )
        (stage / PAGE).write_text(render_page((PUBLIC / "index.html").read_text(encoding="utf-8"), api), encoding="utf-8")

        # Replace only the paths this component owns.
        (out / PAGE).unlink(missing_ok=True)
        shutil.rmtree(out / ASSET_DIR, ignore_errors=True)
        shutil.move(str(stage / PAGE), out / PAGE)
        shutil.move(str(assets), out / ASSET_DIR)
    print(f"Lounge -> {out / PAGE} (API {api})")


if __name__ == "__main__":
    main()
