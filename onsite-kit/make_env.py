#!/usr/bin/env python3
"""Put the links to the Live Database tabs into .onsite_env. Run on an organizer's machine, not on the MacBooks.

The links come from the env files of pull_from_google_sheet.py (and .env). Each MacBook reads the tabs itself
(livedb.py), so this needs running again only when a tab is added or moved, not when the sheets change.
Rewrites only the part of .onsite_env under the GENERATED line, so the lines above it survive.

  uv run --env-file low_keys/real.env --env-file high_keys/real.env python onsite-kit/make_env.py
"""

import os
import re
from pathlib import Path

import dotenv

KIT = Path(__file__).resolve().parent
ROOT = KIT.parent
ENV_FILE = KIT / '.onsite_env'
TEMPLATE = KIT / 'onsite_env.example'
GENERATED = '# ----- GENERATED by make_env.py: edits below this line are overwritten -----'
# The Live Database tabs of the website's own env files, as SHEET_<name> in .onsite_env.
SHEETS = {'PAPERS_SHEET_URL': 'PAPERS', 'EVENTS_SHEET_URL': 'EVENTS', 'SESSION_ASSIGNMENT_SHEET_URL': 'SESSION_ASSIGNMENT',
          'LBDS_SHEET_URL': 'LBDS', 'LBDS_GROUPING': 'LBD_GROUPS'}


def main():
    dotenv.load_dotenv(ROOT / '.env')
    source = ENV_FILE if ENV_FILE.exists() else TEMPLATE
    by_hand = source.read_text(encoding='utf-8').split(GENERATED)[0].rstrip()
    drive = dict(re.findall(r'^DRIVE_FOLDER_(\w+)=(\S+)', by_hand, re.M))
    if not {'LBD', 'MIREX'} <= set(drive) or 'example' in by_hand.split('DRIVE_FOLDER_')[1]:
        raise SystemExit('Set DRIVE_FOLDER_LBD and DRIVE_FOLDER_MIREX in .onsite_env first')
    lines = []
    for key, name in SHEETS.items():
        url = os.environ.get(key, '').strip().strip('"')
        if url:
            lines.append(f'SHEET_{name}={url}')
        else:
            print(f'{key} is not in the env files: SHEET_{name} left out')
    if not re.search(r'^SHEET_(ORAL|AWARD)_SESSIONS=https', by_hand, re.M):
        print('No SHEET_ORAL_SESSIONS or SHEET_AWARD_SESSIONS above the GENERATED line: no talk sessions')
    ENV_FILE.write_text('\n'.join([by_hand, '', GENERATED, *lines, '']), encoding='utf-8')
    print(f'{ENV_FILE.name}: {len(lines)} sheet links')


if __name__ == '__main__':
    main()
